/* =====================================================================
   Движение текста "Name" за null'ом с учётом ширины текста
   ---------------------------------------------------------------------
   null "Null 2" едет по X от NULL_START до NULL_END. Текст "Name" едет за
   ним по формуле  Name.x = Null.x / C(width)  — чем шире текст, тем меньше
   коэффициент C и тем длиннее путь текста.

   Модель подтверждена двумя замерами:
        ширина 466.0  -> C = 2.35
        ширина 761.3  -> C = 1.73

   Так как делится АБСОЛЮТНАЯ позиция, определяющая величина — конечная
   позиция текста при Null.x = NULL_END:  NULL_END / C.
   Оказалось, что она растёт ровно на ширину текста:
        конечная позиция = width + K
   =>   C(width) = NULL_END / (width + K)

   Калибровка K по замерам:
        1913 / 2.35 - 466.0 = 348.0
        1913 / 1.73 - 761.3 = 344.5   ->   K ≈ 346
   ===================================================================== */

var NULL_START = 326;    // старт null'а по X (для checkPos и т.п.)
var NULL_END   = 1913;   // финиш null'а по X
var K = 346;             // добавка к ширине (из калибровки по двум точкам)

// Коэффициент для произвольной ширины текста.
function speedCoeff(width)
{
    return NULL_END / (width + K);
}

function setEndPos()
{
    var width = thisComp.layer("Name").sourceRectAtTime(false).width;
    thisComp.layer("Name").transform.position.x =
        thisComp.layer("Null 2").transform.position.x / speedCoeff(width);
}


/* ---------------------------------------------------------------------
   Если понадобится пересчитать K по двум своим точкам (w1,C1) и (w2,C2)
   без ручной подстановки — можно так (усреднение двух оценок):

     function calibrateK(w1, C1, w2, C2) {
         return ((NULL_END / C1 - w1) + (NULL_END / C2 - w2)) / 2;
     }
     K = calibrateK(466, 2.35, 761.3, 1.73);   // ≈ 346
   --------------------------------------------------------------------- */
