/* =====================================================================
   fitTextWidth — подгонка масштаба текста под ширину
   ---------------------------------------------------------------------
   Если текст шире maxWidth — уменьшает масштаб слоя, чтобы влез;
   иначе возвращает 100%. Мерит натуральную ширину, поэтому её можно
   звать хоть каждый кадр.

   Если в твоём скрипте scale задаётся присваиванием, замени последнюю
   строку на:  layer.transform.scale = [pct, pct, 100];
   ===================================================================== */

function fitTextWidth(layer, maxWidth)
{
    var w = layer.sourceRectAtTime(false).width;
    var pct = w > maxWidth ? maxWidth / w * 100 : 100;
    layer.transform.scale.setValue([pct, pct, 100]);
}
